"""Candidate: image-conditioned ControlNet sample-plan assembly and generation (issue #61).

The trained counterpart of the zero-training img2img baseline. Runs the four-anchor-
round protocol over a manifest side with the frozen P1-DM + the run's trained
ControlNet checkpoint (``controlnet-candidate``): each real modality anchors one
round, the other three target modalities are generated by conditioning the
frozen DM on the anchor's 4ch src latent (with the target modality label riding
the ``class_labels`` path into both DM and ControlNet) and denoising from pure
noise with CFG OFF (``cfg_guidance_scale == 0``, zero latent unconditional
branch — issue #61 acceptance criterion 1-2). It is *not* an interpolated image
start, it is a ControlNet condition.

Outputs (controlled storage, shard-suffixed when ``--num-shards > 1``):

- ``generated/<CH>/<case>/a<src>/<tgt>_seed<seed>.nii.gz`` — candidate volumes;
- ``reference_grid/<CH>/<case>/<tgt>.nii.gz`` — real target volumes resampled
  onto the generation grid (RAS + trilinear 256x256x128, raw intensity domain),
  shared with the baseline run so reference/baseline/candidate triplets align;
- ``samples<...>.json`` — distribution ``four-anchor-plan``-compatible candidate entries
  (variant=controlnet-candidate); the distribution final-acceptance assembly consumes it
  directly;
- ``pairs<...>.json`` — quantitative-side flat candidate records. The full quantitative pair
  triplets are merged by the manifest ``pairs`` builder from the baseline
  reference records plus these candidate volumes.

Run order: select/freeze the candidate first (the run must be frozen before
generation), then ``--side dev`` as a small smoke that only validates the
inference pipeline (its samples are a dev cot; they are not bound to the
contract). The quantitative/distribution/expert-review deliverables it must be auditable against use the
``--side holdout`` samples manifest.

The plan-layer pieces (inference-config validation, run guard, sample plan
builder) are pure logic — stdlib only, no torch/nibabel; the manifest layer came
from the retired candidate plan entry. The generation driver came from the retired
candidate generate entry (ticket 08, ADR-0015 §2); their ``selftest`` subcommands
retired with them.

Usage::

    ctmr generate cross-modal generate candidate \
        --run runs/p3-candidate-.../run.json \
        --manifest /ctrl/phase/phase_manifest.json \
        --out-root /ctrl/p3/candidate_holdout \
        --raw-root /ctrl/phase/raw \
        --stage0-pairs /ctrl/p3/stage0_holdout/pairs.json \
        -e configs/environment_maisi_diff_model_rflow-mr-brain.json \
        -c configs/config_maisi_diff_model_rflow-mr-brain.json \
        -t configs/config_network_p3.json \
        --infer-config configs/config_p3_controlnet_infer.json \
        [--side holdout] [--shard 0 --num-shards 8] [--limit N] [--challenge GLI]
"""

